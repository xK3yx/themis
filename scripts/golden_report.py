"""Coverage report for the table-parser golden fixtures (M1 spec §10.2).

    uv run python scripts/golden_report.py          # print and write COVERAGE.md
    uv run python scripts/golden_report.py --check  # exit 1 if COVERAGE.md is stale

Generated from the fixtures themselves, so the committed report can't drift from them
(tests/extract/test_golden_fixtures.py runs --check).
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "src"))

from tests.extract.golden import CASES, load_goldens  # noqa: E402
from tests.extract.golden import ROOT as GOLDEN_ROOT  # noqa: E402

OUT = GOLDEN_ROOT / "COVERAGE.md"
CASE_NAMES = {
    "C1": "multicolumn",
    "C2": "multirow",
    "C3": "nested spans",
    "C4": "header paths",
    "C5": "bold/italic/underline",
    "C6": "column-wide style",
    "C7": "colour",
    "C8": "plus-minus",
    "C9": "number formats",
    "C10": "missing values",
    "C11": "arrows",
    "C12": "footnote marks",
    "C13": "rules / core grid",
    "C14": "environments",
    "C15": "preamble macros",
    "C16": "unknown macros",
    "C17": "short rows padded",
    "C18": "\\input tables",
    "C19": "image tables",
    "C20": "transposed",
}


def licence_short(url: str | None) -> str:
    if not url:
        return "?"
    if url == "synthetic":
        return "synthetic"
    parts = url.rstrip("/").split("/")
    return f"CC {parts[-2].upper()} {parts[-1]}" if "creativecommons" in url else url


def render() -> str:
    goldens = load_goldens()
    real = [g for g in goldens if not g.synthetic]
    synth = [g for g in goldens if g.synthetic]
    papers = sorted({g.meta["arxiv_id"] for g in real})
    lines = [
        "# Golden table fixtures: coverage",
        "",
        "Generated by `scripts/golden_report.py` from the fixtures; do not edit by hand.",
        "",
        f"- Real tables: **{len(real)}** from **{len(papers)}** papers "
        "(licence read from arXiv OAI-PMH, recorded per paper)",
        f"- Synthetic tables: **{len(synth)}**, only for cases no surveyed licensed table "
        "contained",
        f"- Cells hand-written: **{sum(len(t.cells) for g in goldens for t in g.tables)}**",
        "",
        "| Golden | Kind | Licence | " + " | ".join(CASES) + " |",
        "|---|---|---|" + "---|" * len(CASES),
    ]
    for g in goldens:
        kind = "SYNTHETIC" if g.synthetic else "real"
        lic = licence_short(g.meta.get("license"))
        marks = " | ".join("x" if c in g.cases else "" for c in CASES)
        lines.append(f"| {g.id} | {kind} | {lic} | {marks} |")
    lines += ["", "| Case | | Real tables | Synthetic tables |", "|---|---|---|---|"]
    for c in CASES:
        r = [g.id for g in real if c in g.cases]
        s = [g.id for g in synth if c in g.cases]
        lines.append(f"| {c} | {CASE_NAMES[c]} | {len(r)} | {len(s)} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("COVERAGE.md is stale: run scripts/golden_report.py")
            return 1
        return 0
    OUT.write_bytes(text.encode())
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
